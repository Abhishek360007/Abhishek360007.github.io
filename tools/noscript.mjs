// Builds the no-JavaScript fallback in index.html from data.js.
//
// The live page is rendered by script.js, so with JavaScript off (or for crawlers
// that don't run it) the page would be nearly empty. This writes a plain-HTML copy
// of the portfolio into a <noscript> block between the markers in index.html.
//
// Run it after editing data.js:   node tools/noscript.mjs
// Check it is up to date:         node tools/noscript.mjs --check   (exits 1 if stale)

import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const P = new Function(`${readFileSync(new URL('data.js', root), 'utf8')}; return PORTFOLIO;`)();

const START = '<!-- noscript:start (generated by tools/noscript.mjs from data.js; do not edit by hand) -->';
const END = '<!-- noscript:end -->';

const esc = s => String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
// Descriptions in data.js contain trusted <b> markup only; keep <b>, escape everything else.
const rich = s => esc(s).replace(/&lt;(\/?)b&gt;/g, '<$1b>');
const link = (href, text) => `<a href="${esc(href)}" target="_blank" rel="noopener">${esc(text)}</a>`;

const projects = P.projects
  .map(p => {
    const [name, sub] = p.title.split(/:\s+/);
    const links = [p.live && link(p.live, 'Live demo'), p.github && link(p.github, 'Code')].filter(Boolean).join(' · ');
    return `        <li>
          <h3>${esc(name)}${sub ? ` <small>${esc(sub)}</small>` : ''}</h3>
          <p>${rich(p.description)}</p>
          <p class="ns-meta">${p.tags.map(esc).join(', ')}${links ? ` · ${links}` : ''}</p>
        </li>`;
  })
  .join('\n');

const jobs = P.experience
  .map(
    e => `        <li>
          <h3>${esc(e.role)}, ${esc(e.company)} <small>${esc(e.period)} · ${esc(e.location)}</small></h3>
          <ul>${e.points.map(pt => `<li>${rich(pt)}</li>`).join('')}</ul>
        </li>`,
  )
  .join('\n');

const skills = P.skills.map(g => `        <li><strong>${esc(g.group)}:</strong> ${g.items.map(([n]) => esc(n)).join(', ')}</li>`).join('\n');

const education = P.education
  .map(e => `        <li><h3>${esc(e.degree)} <small>${esc(e.school)} · ${esc(e.period)}</small></h3><p>${rich(e.description)}</p></li>`)
  .join('\n');

const certs = P.certifications
  .map(c => `        <li><strong>${esc(c.title)}${c.badge ? ` (${esc(c.badge)})` : ''}:</strong> ${esc(c.issuer)}</li>`)
  .join('\n');

const socials = P.socials.filter(s => !s.url.startsWith('mailto:')).map(s => link(s.url, s.name)).join(' · ');

const block = `${START}
  <noscript>
    <style>
      main > :not(noscript), #footerText { display: none !important; }
      .reveal { opacity: 1 !important; transform: none !important; }
      .ns { max-width: 820px; margin: 0 auto; padding: 110px 20px 40px; line-height: 1.6; }
      .ns h1 { font-size: clamp(2.2rem, 6vw, 3.4rem); margin-bottom: 4px; }
      .ns h2 { font-size: 1.5rem; margin: 40px 0 12px; }
      .ns h3 { font-size: 1.1rem; margin: 18px 0 4px; }
      .ns small { color: var(--muted); font-weight: 400; font-size: 0.85em; }
      .ns ul { padding-left: 20px; }
      .ns > ul { list-style: none; padding: 0; }
      .ns p, .ns li { color: var(--text); }
      .ns .ns-meta { color: var(--muted); font-size: 0.9rem; }
      .ns a { color: var(--accent); text-decoration: underline; }
    </style>
  </noscript>
  <noscript>
    <div class="ns">
      <h1>${esc(P.name)}</h1>
      <p><strong>${esc(P.role)}</strong> · ${esc(P.location)}</p>
      <p>${rich(P.tagline)}</p>
      <p>${link(P.resume, 'Résumé (PDF)')} · <a href="mailto:${esc(P.email)}">${esc(P.email)}</a> · ${socials}</p>

      <h2>About</h2>
${P.about.map(a => `      <p>${rich(a)}</p>`).join('\n')}

      <h2>Projects</h2>
      <ul>
${projects}
      </ul>

      <h2>Skills</h2>
      <ul>
${skills}
      </ul>

      <h2>Experience</h2>
      <ul>
${jobs}
      </ul>

      <h2>Education</h2>
      <ul>
${education}
      </ul>

      <h2>Achievements &amp; certifications</h2>
      <ul>
${certs}
      </ul>

      <h2>Contact</h2>
      <p><a href="mailto:${esc(P.email)}">${esc(P.email)}</a> · ${esc(P.phone)} · ${esc(P.location)}</p>
    </div>
  </noscript>
  ${END}`;

const file = new URL('index.html', root);
const html = readFileSync(file, 'utf8');
const a = html.indexOf(START.slice(0, 20));
const b = html.indexOf(END);
if (a < 0 || b < 0) {
  console.error('index.html: noscript markers not found');
  process.exit(1);
}
const next = html.slice(0, a) + block + html.slice(b + END.length);

if (process.argv.includes('--check')) {
  if (next !== html) {
    console.error('index.html: the no-JavaScript fallback is out of date. Run: node tools/noscript.mjs');
    process.exit(1);
  }
  console.log('index.html: no-JavaScript fallback is up to date');
} else {
  writeFileSync(file, next);
  console.log(`index.html: wrote no-JavaScript fallback (${P.projects.length} projects)`);
}
